using System.Text;
using System.Text.Json;
using ApiClientGenerator.Abstractions.Abstractions;
using ApiClientGenerator.Abstractions.Models;

namespace ApiClientGenerator.React;

public sealed class TypeScriptModelEmitter(ITypeMapper typeMapper) : IModelEmitter
{
    public string FileExtension => ".ts";

    public string Emit(
        IReadOnlyCollection<string> models,
        IReadOnlyDictionary<string, OpenApiSchema> allSchemas)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// Этот файл сгенерирован автоматически. Не редактируйте вручную.");
        sb.AppendLine();

        var ordered = models
            .Where(allSchemas.ContainsKey)
            .OrderBy(m => allSchemas[m].Enum is { Count: > 0 } ? 0 : 1)
            .ThenBy(m => m)
            .ToList();

        foreach (var name in ordered)
        {
            var schema = allSchemas[name];

            if (schema.Enum is { Count: > 0 })
                EmitEnum(sb, name, schema);
            else
                EmitInterface(sb, name, schema);
        }

        return sb.ToString();
    }

    private static void EmitEnum(StringBuilder sb, string name, OpenApiSchema schema)
    {
        sb.AppendLine($"export enum {name} {{");

        foreach (var str in schema.Enum!
                     .Select(value => value.ValueKind == JsonValueKind.String
                         ? value.GetString()!
                         : value.ToString()))
        {
            var member = new string(str.Where(char.IsLetterOrDigit).ToArray());
            if (string.IsNullOrEmpty(member)) member = "_";

            sb.AppendLine($"  {member} = \"{str}\",");
        }

        sb.AppendLine("}");
        sb.AppendLine();
    }

    private void EmitInterface(StringBuilder sb, string name, OpenApiSchema schema)
    {
        sb.AppendLine($"export interface {name} {{");

        if (schema.Properties is null or { Count: 0 })
        {
            sb.AppendLine("  [key: string]: unknown;");
            sb.AppendLine("}");
            sb.AppendLine();
            return;
        }

        foreach (var (propName, propSchema) in schema.Properties)
        {
            var tsType = ResolveType(propSchema, false);
            var optional = propSchema.Nullable ? "?" : "";
            sb.AppendLine($"  {propName}{optional}: {tsType};");
        }

        sb.AppendLine("}");
        sb.AppendLine();
    }

    private string ResolveType(OpenApiSchema schema, bool isLocal)
    {
        if (schema.Ref is not null)
        {
            var name = schema.Ref.Split('/')[^1];
            return typeMapper.MapReference(name, isLocal);
        }

        if (schema.Enum is { Count: > 0 })
            return "string";

        var baseType = schema.Type switch
        {
            "string" => typeMapper.MapPrimitive("string", schema.Format),
            "integer" or "number" => typeMapper.MapPrimitive(schema.Type, schema.Format),
            "boolean" => typeMapper.MapPrimitive("boolean", schema.Format),
            "array" => schema.Items is not null
                ? typeMapper.MapArray(ResolveType(schema.Items, isLocal))
                : typeMapper.MapArray(typeMapper.MapUnknown()),
            "object" => typeMapper.MapObject(),
            _ => typeMapper.MapUnknown()
        };

        return schema.Nullable ? typeMapper.MakeNullable(baseType) : baseType;
    }
}