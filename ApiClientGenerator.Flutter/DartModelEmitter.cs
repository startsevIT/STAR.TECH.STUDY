using System.Text;
using System.Text.Json;
using ApiClientGenerator.Abstractions.Abstractions;
using ApiClientGenerator.Abstractions.Models;

namespace ApiClientGenerator.Flutter;

public sealed class DartModelEmitter(ITypeMapper typeMapper) : IModelEmitter
{
    public string FileExtension => ".dart";

    public string Emit(
        IReadOnlyCollection<string> models,
        IReadOnlyDictionary<string, OpenApiSchema> allSchemas)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// Этот файл сгенерирован автоматически. Не редактируйте вручную.");
        sb.AppendLine();

        var ordered = models
            .Where(allSchemas.ContainsKey)
            .OrderBy(m => allSchemas[m].Enum is { Count: > 0 } ? 0 : 1)
            .ThenBy(m => m)
            .ToList();

        foreach (var name in ordered)
        {
            var schema = allSchemas[name];

            if (schema.Enum is { Count: > 0 })
                EmitEnum(sb, name, schema);
            else
                EmitClass(sb, name, schema);
        }

        return sb.ToString();
    }

    private static void EmitEnum(StringBuilder sb, string name, OpenApiSchema schema)
    {
        sb.AppendLine($"enum {name} {{");

        var values = schema.Enum!
            .Select(value => value.ValueKind == JsonValueKind.String
                ? value.GetString()!
                : value.ToString())
            .ToList();

        foreach (var str in values)
        {
            var member = new string(str.Where(char.IsLetterOrDigit).ToArray());
            if (string.IsNullOrEmpty(member)) member = "_";

            sb.AppendLine($"  {char.ToLowerInvariant(member[0])}{member[1..]}('{str}'),");
        }

        sb.AppendLine("  ;");
        sb.AppendLine();
        sb.AppendLine($"  const {name}(this.value);");
        sb.AppendLine();
        sb.AppendLine("  final String value;");
        sb.AppendLine();
        sb.AppendLine($"  static {name} fromJson(String value) =>");
        sb.AppendLine($"      {name}.values.firstWhere((e) => e.value == value);");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private void EmitClass(StringBuilder sb, string name, OpenApiSchema schema)
    {
        var properties = schema.Properties ?? new Dictionary<string, OpenApiSchema>();
        var required = schema.Required?.ToHashSet() ?? [];

        sb.AppendLine($"class {name} {{");

        foreach (var (propName, propSchema) in properties)
        {
            var dartType = ResolveType(propSchema);
            var isRequired = required.Contains(propName) && !propSchema.Nullable;
            var fieldType = isRequired ? dartType : typeMapper.MakeNullable(dartType);
            var fieldName = ToCamelCase(propName);

            sb.AppendLine($"  final {fieldType} {fieldName};");
        }

        sb.AppendLine();
        sb.AppendLine($"  const {name}({{");

        foreach (var (propName, propSchema) in properties)
        {
            var isRequired = required.Contains(propName) && !propSchema.Nullable;
            var fieldName = ToCamelCase(propName);
            var modifier = isRequired ? "required " : "";
            sb.AppendLine($"    {modifier}this.{fieldName},");
        }

        sb.AppendLine("  });");
        sb.AppendLine();

        // fromJson
        sb.AppendLine($"  factory {name}.fromJson(Map<String, dynamic> json) {{");
        sb.AppendLine($"    return {name}(");

        foreach (var (propName, propSchema) in properties)
        {
            var fieldName = ToCamelCase(propName);
            var parseExpr = BuildFromJsonExpression(propSchema, $"json['{propName}']");
            sb.AppendLine($"      {fieldName}: {parseExpr},");
        }

        sb.AppendLine("    );");
        sb.AppendLine("  }");
        sb.AppendLine();

        // toJson
        sb.AppendLine("  Map<String, dynamic> toJson() {");
        sb.AppendLine("    return {");

        foreach (var (propName, propSchema) in properties)
        {
            var fieldName = ToCamelCase(propName);
            var expr = BuildToJsonExpression(propSchema, fieldName);
            sb.AppendLine($"      '{propName}': {expr},");
        }

        sb.AppendLine("    };");
        sb.AppendLine("  }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private string BuildFromJsonExpression(OpenApiSchema schema, string accessor)
    {
        if (schema.Ref is not null)
        {
            var refName = schema.Ref.Split('/')[^1];
            return $"{refName}.fromJson({accessor} as Map<String, dynamic>)";
        }

        if (schema.Enum is { Count: > 0 })
            return $"{accessor} as String";

        if (schema.Type != "array" || schema.Items is null)
            return schema.Type switch
            {
                "string" => schema.Format switch
                {
                    "date-time" or "date" => $"DateTime.parse({accessor} as String)",
                    _ => $"{accessor} as String"
                },
                "integer" => $"{accessor} as int",
                "number" => $"({accessor} as num).toDouble()",
                "boolean" => $"{accessor} as bool",
                "object" => $"{accessor} as Map<String, dynamic>",
                _ => accessor
            };
        
        var itemExpr = BuildFromJsonExpression(schema.Items, "e");
        return $"({accessor} as List<dynamic>).map((e) => {itemExpr}).toList()";

    }

    private string BuildToJsonExpression(OpenApiSchema schema, string fieldName)
    {
        if (schema.Ref is not null)
            return $"{fieldName}.toJson()";

        if (schema is { Type: "array", Items: not null })
        {
            return schema.Items.Ref is not null 
                ? $"{fieldName}.map((e) => e.toJson()).toList()" 
                : fieldName;
        }

        return schema.Format is "date-time" or "date" 
            ? $"{fieldName}.toIso8601String()" 
            : fieldName;
    }

    private string ResolveType(OpenApiSchema schema)
    {
        if (schema.Ref is not null)
        {
            var name = schema.Ref.Split('/')[^1];
            return typeMapper.MapReference(name, false);
        }

        if (schema.Enum is { Count: > 0 })
            return "String";

        var baseType = schema.Type switch
        {
            "string" => typeMapper.MapPrimitive("string", schema.Format),
            "integer" => typeMapper.MapPrimitive("integer", schema.Format),
            "number" => typeMapper.MapPrimitive("number", schema.Format),
            "boolean" => typeMapper.MapPrimitive("boolean", schema.Format),
            "array" => schema.Items is not null
                ? typeMapper.MapArray(ResolveType(schema.Items))
                : typeMapper.MapArray(typeMapper.MapUnknown()),
            "object" => typeMapper.MapObject(),
            _ => typeMapper.MapUnknown()
        };

        return schema.Nullable ? typeMapper.MakeNullable(baseType) : baseType;
    }

    private static string ToCamelCase(string value)
    {
        if (string.IsNullOrEmpty(value)) return value;

        var parts = value.Split(['_', '-', ' '], StringSplitOptions.RemoveEmptyEntries);
        var pascal = string.Concat(parts.Select(p =>
            char.ToUpperInvariant(p[0]) + p[1..]));

        return char.ToLowerInvariant(pascal[0]) + pascal[1..];
    }
}